from __future__ import annotations

from pathlib import Path

import pytest

from codegen import cli


@pytest.fixture
def pkg(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> Path:
    apis = tmp_path / "apis"
    apis.mkdir()
    (apis / "kept.py").write_text("# GENERATED by codegen.\nx = 1\n")
    (apis / "stale.py").write_text("# GENERATED by codegen.\nx = 2\n")
    (apis / "handwritten.py").write_text('"""Hand written."""\n')
    (apis / "_private.py").write_text("# GENERATED by codegen.\n")
    monkeypatch.setattr(cli, "APIS_PKG", apis)
    monkeypatch.setattr(cli, "ROOT", tmp_path)
    monkeypatch.setattr(cli, "spec_paths", lambda: [])

    def fake_build(paths, only=None, include_uncurated=False):  # noqa: ANN001, ARG001
        res = cli.Result()
        res.files[apis / "kept.py"] = "# GENERATED by codegen.\nx = 1\n"
        res.files[apis / "__init__.py"] = "# GENERATED by codegen.\n"
        return res

    monkeypatch.setattr(cli, "build_all", fake_build)
    return apis


def test_generate_removes_stale_generated_modules(pkg: Path, capsys: pytest.CaptureFixture[str]) -> None:
    assert cli.main(["generate"]) == 0
    assert not (pkg / "stale.py").exists()
    assert (pkg / "kept.py").exists() and (pkg / "__init__.py").exists()
    assert "removed apis/stale.py" in capsys.readouterr().out


def test_generate_preserves_handwritten_and_private_files(pkg: Path) -> None:
    cli.main(["generate"])
    assert (pkg / "handwritten.py").exists()
    assert (pkg / "_private.py").exists()


def test_generate_only_deletes_nothing(pkg: Path) -> None:
    assert cli.main(["generate", "--only", "kept"]) == 0
    assert (pkg / "stale.py").exists()


def test_generate_does_not_delete_when_a_spec_failed(pkg: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    original = cli.build_all

    def failing(*a, **k):  # noqa: ANN002, ANN003
        res = original(*a, **k)
        res.errors["specs/x.yaml"] = "boom"
        return res

    monkeypatch.setattr(cli, "build_all", failing)
    assert cli.main(["generate"]) == 1
    assert (pkg / "stale.py").exists()


def test_check_flags_stale_generated_modules(pkg: Path, capsys: pytest.CaptureFixture[str]) -> None:
    (pkg / "__init__.py").write_text("# GENERATED by codegen.\n")
    assert cli.main(["check"]) == 1
    assert "stale.py is generated but no spec produces it" in capsys.readouterr().err
    (pkg / "stale.py").unlink()
    assert cli.main(["check"]) == 0
