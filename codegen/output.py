"""Formatting, the ``apis/__init__.py`` namespace module and the API surface listing."""

from __future__ import annotations

import subprocess
from pathlib import Path

from .loader import ROOT
from .model import ApiDef
from .render import signatures

LINE_LENGTH = "120"
APIS_PKG = ROOT / "src" / "ax_devil_device_api" / "apis"
SURFACE_PATH = ROOT / "docs" / "api_surface.txt"


def _ruff(args: list[str], source: str, filename: str) -> str:
    result = subprocess.run(
        ["ruff", *args, "--isolated", "--line-length", LINE_LENGTH, "--stdin-filename", filename, "-"],
        input=source,
        capture_output=True,
        text=True,
        cwd=ROOT,
    )
    if result.returncode != 0:
        raise RuntimeError(f"ruff {args[0]} failed:\n{result.stderr or result.stdout}")
    return result.stdout


def format_python(source: str, filename: str = "module.py") -> str:
    """Prune unused imports, sort imports, format. Deterministic for a given ruff version."""
    pruned = _ruff(["check", "--select", "F401", "--fix", "--quiet", "--target-version", "py311"], source, filename)
    sorted_ = _ruff(["check", "--select", "I", "--fix", "--quiet", "--target-version", "py311"], pruned, filename)
    return _ruff(["format", "--target-version", "py311"], sorted_, filename)


def render_namespace(apis: list[ApiDef]) -> str:
    apis = sorted(apis, key=lambda a: a.module)
    imports = []
    for a in apis:
        n = a.class_name
        imports.append(f"    from .{a.module} import Async{n}Api, {n}Api")

    def block(cls: str, device: str, prefix: str, doc: str) -> list[str]:
        lines = [
            "",
            "",
            f"class {cls}:",
            f'    """{doc}"""',
            "",
            f"    def __init__(self, device: {device}) -> None:",
            "        self._device = device",
        ]
        for a in apis:
            name = f"{prefix}{a.class_name}Api"
            lines += [
                "",
                "    @cached_property",
                f"    def {a.module}(self) -> {name}:",
                f"        from .{a.module} import {name}",
                "",
                f"        return self._device.api({name})",
            ]
        return lines

    text = [
        "# GENERATED by codegen. Do not edit.",
        "# Regenerate with `uv run python -m codegen generate`.",
        '"""Namespaces exposing every generated API as ``device.apis.<name>``."""',
        "",
        "from __future__ import annotations",
        "",
        "from functools import cached_property",
        "from typing import TYPE_CHECKING",
        "",
        "if TYPE_CHECKING:",
        "    from ..device import AsyncDevice, Device",
        *imports,
        *block("Apis", "Device", "", "Every API, for a blocking ``Device``. Modules are imported on first use."),
        *block("AsyncApis", "AsyncDevice", "Async", "Every API, for an ``AsyncDevice``. Modules are imported on first use."),
        "",
    ]
    return format_python("\n".join(text), "src/ax_devil_device_api/apis/__init__.py")


def render_surface(apis: list[ApiDef]) -> str:
    lines: list[str] = []
    for a in apis:
        m = a.module
        for td in a.types:
            if td.kind == "alias":
                lines.append(f"{m}.{td.name} = {td.alias_expr}")
                continue
            fields = []
            for f in td.fields:
                opt = not f.required or f.nullable
                ann = f.ann + (" | None" if opt and f.default is None and not f.ann.endswith("None") else "")
                wire = f" [{f.wire}]" if f.wire != f.py else ""
                fields.append(f"{f.py}: {ann}{wire}")
            lines.append(f"{m}.{td.name}({', '.join(fields)})")
            if td.round_trip:
                lines.append(f"{m}.{td.name}.from_current({td.round_trip.from_name})")
        for prefix in ("", "Async"):
            cls = f"{prefix}{a.class_name}Api"
            for op in a.ops:
                overloads, impl = signatures(op)
                for sig in overloads:
                    lines.append(f"{m}.{cls}.{op.id}(self, {', '.join(sig.args)}) -> {sig.returns}")
    return "\n".join(sorted(lines)) + "\n"


def module_path(api: ApiDef) -> Path:
    return APIS_PKG / f"{api.module}.py"
